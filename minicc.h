// ============================================================================
// minicc.h — встроенный мини-компилятор выражений AI-OS (Phase 6, Mint)
// ============================================================================
// Честный компиляторный пайплайн во freestanding-ядре (без libc/LLVM):
//   исходник -> токены -> байткод (стековая VM) -> выполнение.
// Поддерживает команды shell: cc / cxx / objc / swift / build / samples.
// Языковые фишки хоста (шаблоны C++, ARC/NS ST, Swift-опционалы) недоступны
// в bare-metal: здесь — общий арифметический кор с синтаксическими
// обёртками каждого языка (см. kernel.c). Полные тулчейны — на хосте:
//   build.sh собирает samples/*.c/*.cpp/*.m через gcc/g++/clang+GNUstep,
//   а Swift — через swiftc при его наличии.
// Ограничения: целые 32 бит, длина входа <= 192, глубина скобок <= 24,
// код <= 64 инструкций, стек VM 32. Деление на ноль = ошибка (не panic).
// ============================================================================
#ifndef MINICC_H
#define MINICC_H

// Скомпилировать src и выполнить. Возвращает 0 при успехе, иначе -1.
// При ошибке в err (до errn байт) лежит причина, out_result не тронут.
int mini_compile_run(const char *src, int *out_result, char *err, int errn);

// То же, но с листингом стадий (токены, байткод, запуск) в log (logn байт).
int mini_build_verbose(const char *src, int *out_result, char *log, int logn);

#endif
