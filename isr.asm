; ============================================================================
; isr.asm — Interrupt Service Routine stubs
; ============================================================================
;
; Эти функции вызываются CPU при прерывании или исключении.
; Они определены как ассемблерные обработчики для IDT.
;
; CPU при прерывании автоматически сохраняет на стек:
;   RIP, CS, RFLAGS, RSP, SS (если смена привилегий)
;
; Мы дополнительно сохраняем GP регистры (RAX-R15) вручную.
; ============================================================================

[BITS 64]

global default_exception_handler
global default_irq_handler

section .note.GNU-stack
    dd 0, 0, 0, 0
section .text

; ---------------------------------------------------------------------------
; default_exception_handler — обработчик исключений (divide by zero, page fault, etc.)
; ---------------------------------------------------------------------------
; Если произошло исключение CPU (вектор 0-31), мы попадаем сюда.
; Мы не можем безопасно продолжить, поэтому останавливаемся в HLT.
; ---------------------------------------------------------------------------
default_exception_handler:
halt_loop:
    hlt                  ; Останавливаем CPU (энергосбережение)
    jmp halt_loop          ; Бесконечный цикл HLT -> JMP

; ---------------------------------------------------------------------------
; default_irq_handler — обработчик IRQ по умолчанию
; ---------------------------------------------------------------------------
; Этот обработчик вызывается для IRQ, которые мы не хотим обрабатывать специально
; (все IRQ, кроме клавиатуры IRQ1).
;
; Ему нужно:
;   1. Сохранить RAX (мы используем AL для outb).
;   2. Отправить EOI (End Of Interrupt) в PIC.
;   3. Восстановить RAX.
;   4. Вернуться через iretq.
;
; EOI отправляется записью 0x20 в порт команд PIC:
;   - Port 0x20: магистральный PIC (master, IRQ0-7)
;   - Port 0xA0: подчинённый PIC (slave, IRQ8-15)
;
; Мы отправляем EOI в оба контроллера, чтобы безопасно обработать любое IRQ.
; ---------------------------------------------------------------------------
default_irq_handler:
    push rax               ; Сохраняем RAX (мы будем использовать AL)
    mov al, 0x20           ; 0x20 = EOI (End Of Interrupt) команда для PIC

    ; Отправляем EOI в подчинённый PIC.
    ; Это безопасно даже для IRQ от магистрального PIC —
    ; запись в slave не повлияет на master.
    out 0xA0, al

    ; Отправляем EOI в магистральный PIC.
    out 0x20, al

    pop rax                ; Восстанавливаем RAX
    iretq                  ; Возврат из прерывания:
                           ;   Снимает со стека RIP, CS, RFLAGS, RSP, SS
