// ============================================================================
// mouse.h — Минимальный PS/2 mouse driver (для оконного менеджера)
// ============================================================================
// IRQ12 -> вектор 0x2C, 3-байтные пакеты. Курсор в пикселях экрана
// (кламп к 1024x768, WM сам маппит на свой размер). Левая кнопка — drag/focus.
// Инициализация fail-soft с таймаутами: без мыши просто нет курсора,
// клавиатура и остальное продолжают работать.
// ============================================================================
#ifndef MOUSE_H
#define MOUSE_H

#include <stdint.h>

void mouse_init(void);
int mouse_present(void);

// Состояние (обновляется в IRQ12). Кнопки: бит 0 — левая.
int mouse_x(void);
int mouse_y(void);
uint8_t mouse_buttons(void);

#endif
