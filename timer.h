// ============================================================================
// timer.h — Системный таймер PIT 8254, 100 Гц (IRQ0 -> вектор 0x20)
// ============================================================================
#ifndef TIMER_H
#define TIMER_H

#include <stdint.h>

#define TIMER_HZ 100

// Настройка PIT (1193180 / 100 Гц) и установка IDT-записи 0x20.
// Размаскирует IRQ0. Вызывать после idt_init().
void timer_init(void);

// C-часть тика (вызывается из timer_irq_handler). Инкремент счётчика + EOI
// отправляется в ASM-стабе; здесь только счётчик (и опционально планировщик).
void timer_tick(void);

// Миллисекунды с момента timer_init().
uint64_t uptime_ms(void);

// Точный (coarse) сон: крутится на HLT до истечения ms.
void sleep_ms(uint32_t ms);

// Сырое число тиков (1 тик = 10 мс при 100 Гц).
uint64_t timer_ticks(void);

#endif
